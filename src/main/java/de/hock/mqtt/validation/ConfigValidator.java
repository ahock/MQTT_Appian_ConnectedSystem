package de.hock.mqtt.validation;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Design-time validator for the connection, credential, and session configuration fields of the
 * MQTT Connected System.
 *
 * <p>This validator operates on the raw, untyped values a Designer enters (text, possibly empty or
 * non-numeric) so it can report precise, field-scoped errors for empty, non-integer, and
 * out-of-range input while retaining what was typed (Requirements 1.1, 1.3, 1.4, 1.5, 1.7, 2.1,
 * 2.4, 8.4, 8.5, 8.6). Each concern is validated by a discrete public method:
 *
 * <ul>
 *   <li>{@link #validateConnectionFields} — broker host, port, client identifier, connection
 *       timeout.</li>
 *   <li>{@link #validateCredentials} — username/password both-or-neither and length.</li>
 *   <li>{@link #validateSession} — keep-alive bounds and persistent-session client-id
 *       requirement.</li>
 * </ul>
 *
 * <p>The validator is deliberately open for extension: sibling validators own LWT, reconnection,
 * certificate-load, and client-identifier auto-generation concerns in their own classes and merge
 * their {@link ValidationResults} with the ones produced here, so none of them needs to edit this
 * file. {@link #validateAll} is a convenience that runs the three concerns this class owns and
 * returns a single merged result set.
 *
 * <p>Numeric fields are passed as {@link String} because an empty or non-integer entry is itself a
 * validation failure that must be reported with the entered value retained; accepting a parsed
 * {@code int} would hide those cases.
 */
public final class ConfigValidator {

  private static final int HOST_MAX = 253;
  private static final int PORT_MIN = 1;
  private static final int PORT_MAX = 65535;
  private static final int CLIENT_ID_MIN = 1;
  private static final int CLIENT_ID_MAX = 65535;
  private static final int TIMEOUT_MIN = 1;
  private static final int TIMEOUT_MAX = 300;
  private static final int CREDENTIAL_MIN = 1;
  private static final int CREDENTIAL_MAX = 256;
  private static final int KEEP_ALIVE_MIN = 0;
  private static final int KEEP_ALIVE_MAX = 65535;

  /** Default connection timeout in seconds when the field is left blank (Req 1.3). */
  public static final int DEFAULT_CONNECTION_TIMEOUT_SECONDS = 30;

  /** Default keep-alive interval in seconds when the field is left blank (Req 8.4). */
  public static final int DEFAULT_KEEP_ALIVE_SECONDS = 60;

  /**
   * Validates the connection field group: broker host, broker port, client identifier, and
   * connection timeout (Requirements 1.1, 1.3, 1.4, 1.5, 1.7).
   *
   * <ul>
   *   <li>Host must be non-blank and 1–253 characters (Req 1.1, 1.5).</li>
   *   <li>Port must be an integer in 1–65535 (Req 1.1, 1.4).</li>
   *   <li>Client identifier, when provided, must be 1–65535 characters; a blank value is accepted
   *       here because it is auto-generated by a sibling validator (Req 1.1, 1.2).</li>
   *   <li>Connection timeout, when provided, must be an integer in 1–300; a blank value is accepted
   *       and defaults to {@value #DEFAULT_CONNECTION_TIMEOUT_SECONDS} (Req 1.3, 1.7).</li>
   * </ul>
   *
   * @param brokerHost the entered broker host (raw)
   * @param brokerPort the entered broker port (raw)
   * @param clientIdentifier the entered client identifier (raw; may be blank)
   * @param connectionTimeoutSeconds the entered connection timeout (raw; may be blank)
   * @return a result set with one error per offending field, empty when all fields are valid
   */
  public ValidationResults validateConnectionFields(
      String brokerHost,
      String brokerPort,
      String clientIdentifier,
      String connectionTimeoutSeconds) {
    ValidationResults results = new ValidationResults();

    // Broker host: non-blank, 1-253 characters (Req 1.1, 1.5).
    if (isBlank(brokerHost)) {
      results.add(
          ValidationResult.of(
              ConfigFields.BROKER_HOST,
              "Broker host is required and must not be empty.",
              brokerHost));
    } else if (brokerHost.length() > HOST_MAX) {
      results.add(
          ValidationResult.of(
              ConfigFields.BROKER_HOST,
              "Broker host must be between 1 and " + HOST_MAX + " characters.",
              brokerHost));
    }

    // Broker port: integer in 1-65535 (Req 1.1, 1.4).
    Integer port = parseInteger(brokerPort);
    if (isBlank(brokerPort) || port == null || port < PORT_MIN || port > PORT_MAX) {
      results.add(
          ValidationResult.of(
              ConfigFields.BROKER_PORT,
              "Broker port must be a whole number between "
                  + PORT_MIN
                  + " and "
                  + PORT_MAX
                  + ".",
              brokerPort));
    }

    // Client identifier: optional, but when provided must be 1-65535 characters (Req 1.1).
    if (!isBlank(clientIdentifier)
        && (clientIdentifier.length() < CLIENT_ID_MIN
            || clientIdentifier.length() > CLIENT_ID_MAX)) {
      results.add(
          ValidationResult.of(
              ConfigFields.CLIENT_IDENTIFIER,
              "Client identifier must be between "
                  + CLIENT_ID_MIN
                  + " and "
                  + CLIENT_ID_MAX
                  + " characters.",
              clientIdentifier));
    }

    // Connection timeout: optional (defaults to 30), else integer in 1-300 (Req 1.3, 1.7).
    if (!isBlank(connectionTimeoutSeconds)) {
      Integer timeout = parseInteger(connectionTimeoutSeconds);
      if (timeout == null || timeout < TIMEOUT_MIN || timeout > TIMEOUT_MAX) {
        results.add(
            ValidationResult.of(
                ConfigFields.CONNECTION_TIMEOUT_SECONDS,
                "Connection timeout must be a whole number of seconds between "
                    + TIMEOUT_MIN
                    + " and "
                    + TIMEOUT_MAX
                    + ".",
                connectionTimeoutSeconds));
      }
    }

    return results;
  }

  /**
   * Validates the credential pair: username and password must be both present (each 1–256
   * characters) or both absent (Requirements 2.1, 2.4). A single-sided or over-length entry is
   * rejected with values retained.
   *
   * @param username the entered username (raw; may be blank)
   * @param password the entered password (raw; may be blank)
   * @return a result set describing any credential error, empty when the pair is valid
   */
  public ValidationResults validateCredentials(String username, String password) {
    ValidationResults results = new ValidationResults();

    boolean hasUsername = !isBlank(username);
    boolean hasPassword = !isBlank(password);

    // Both-or-neither rule (Req 2.4).
    if (hasUsername != hasPassword) {
      Map<String, String> retained = new LinkedHashMap<>();
      retained.put(ConfigFields.USERNAME, username);
      retained.put(ConfigFields.PASSWORD, password);
      String missingField = hasUsername ? ConfigFields.PASSWORD : ConfigFields.USERNAME;
      results.add(
          new ValidationResult(
              missingField,
              "Username and password must both be provided or both be omitted.",
              retained));
      return results;
    }

    // When both are present, each must be 1-256 characters (Req 2.1).
    if (hasUsername && username.length() > CREDENTIAL_MAX) {
      results.add(
          ValidationResult.of(
              ConfigFields.USERNAME,
              "Username must be between " + CREDENTIAL_MIN + " and " + CREDENTIAL_MAX
                  + " characters.",
              username));
    }
    if (hasPassword && password.length() > CREDENTIAL_MAX) {
      results.add(
          ValidationResult.of(
              ConfigFields.PASSWORD,
              "Password must be between " + CREDENTIAL_MIN + " and " + CREDENTIAL_MAX
                  + " characters.",
              password));
    }

    return results;
  }

  /**
   * Validates the session field group: keep-alive bounds and the persistent-session client
   * identifier requirement (Requirements 8.4, 8.5, 8.6).
   *
   * <ul>
   *   <li>Keep-alive, when provided, must be an integer in 0–65535; a blank value is accepted and
   *       defaults to {@value #DEFAULT_KEEP_ALIVE_SECONDS} (Req 8.4, 8.6).</li>
   *   <li>When the clean session is disabled, a client identifier is required (Req 8.5).</li>
   * </ul>
   *
   * @param keepAliveSeconds the entered keep-alive interval (raw; may be blank)
   * @param cleanSession whether a clean session is enabled
   * @param clientIdentifier the entered client identifier (raw; may be blank)
   * @return a result set describing any session error, empty when the group is valid
   */
  public ValidationResults validateSession(
      String keepAliveSeconds, boolean cleanSession, String clientIdentifier) {
    ValidationResults results = new ValidationResults();

    // Keep-alive: optional (defaults to 60), else integer in 0-65535 (Req 8.4, 8.6).
    if (!isBlank(keepAliveSeconds)) {
      Integer keepAlive = parseInteger(keepAliveSeconds);
      if (keepAlive == null || keepAlive < KEEP_ALIVE_MIN || keepAlive > KEEP_ALIVE_MAX) {
        results.add(
            ValidationResult.of(
                ConfigFields.KEEP_ALIVE_SECONDS,
                "Keep-alive interval must be a whole number of seconds between "
                    + KEEP_ALIVE_MIN
                    + " and "
                    + KEEP_ALIVE_MAX
                    + ".",
                keepAliveSeconds));
      }
    }

    // Persistent session requires a client identifier (Req 8.5).
    if (!cleanSession && isBlank(clientIdentifier)) {
      results.add(
          ValidationResult.of(
              ConfigFields.CLIENT_IDENTIFIER,
              "A client identifier is required when the clean session is disabled "
                  + "(persistent session).",
              clientIdentifier));
    }

    return results;
  }

  /**
   * Convenience that runs the connection, credential, and session validations this class owns and
   * returns a single merged result set. Sibling validators (LWT, reconnection, certificate load)
   * can merge their own result sets into the returned instance without this method needing to know
   * about them.
   *
   * @param brokerHost the entered broker host (raw)
   * @param brokerPort the entered broker port (raw)
   * @param clientIdentifier the entered client identifier (raw; may be blank)
   * @param connectionTimeoutSeconds the entered connection timeout (raw; may be blank)
   * @param username the entered username (raw; may be blank)
   * @param password the entered password (raw; may be blank)
   * @param keepAliveSeconds the entered keep-alive interval (raw; may be blank)
   * @param cleanSession whether a clean session is enabled
   * @return the merged result set across all three concerns
   */
  public ValidationResults validateAll(
      String brokerHost,
      String brokerPort,
      String clientIdentifier,
      String connectionTimeoutSeconds,
      String username,
      String password,
      String keepAliveSeconds,
      boolean cleanSession) {
    ValidationResults results = new ValidationResults();
    mergeInto(
        results,
        validateConnectionFields(
            brokerHost, brokerPort, clientIdentifier, connectionTimeoutSeconds));
    mergeInto(results, validateCredentials(username, password));
    mergeInto(results, validateSession(keepAliveSeconds, cleanSession, clientIdentifier));
    return results;
  }

  /** Copies every entry from {@code source} into {@code target}, preserving order. */
  private static void mergeInto(ValidationResults target, ValidationResults source) {
    for (ValidationResult result : source.all()) {
      target.add(result);
    }
  }

  private static boolean isBlank(String value) {
    return value == null || value.isBlank();
  }

  /**
   * Parses a strictly-integer value: no decimals, no surrounding whitespace beyond trimming, no
   * trailing characters. Returns {@code null} when the value is blank or not a valid integer, so
   * callers can report a non-integer entry as a bounds failure.
   */
  private static Integer parseInteger(String value) {
    if (isBlank(value)) {
      return null;
    }
    String trimmed = value.trim();
    try {
      return Integer.valueOf(trimmed);
    } catch (NumberFormatException ex) {
      return null;
    }
  }
}
